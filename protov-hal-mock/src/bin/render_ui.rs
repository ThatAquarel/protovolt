use std::path::Path;

use protov_hal_mock::render::save_snapshot_png;
use protov_hal_mock::state::{StateLoadError, load_state_file};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let states_dir = manifest_dir.join("states");
    let output_dir = manifest_dir.join("..").join("docs").join("res").join("ui");
    let doc_path = manifest_dir.join("..").join("docs").join("ui-states.md");
    std::fs::create_dir_all(&output_dir)?;

    let mut rendered = Vec::new();
    for entry in std::fs::read_dir(&states_dir)? {
        let entry = entry?;
        let path = entry.path();
        if path.extension().and_then(|ext| ext.to_str()) != Some("yaml") {
            continue;
        }
        let file_name = path
            .file_name()
            .and_then(|name| name.to_str())
            .unwrap_or_default()
            .to_owned();
        if !file_name.starts_with("ui-") {
            continue;
        }

        let snapshot = load_state_file(&path)?;
        let stem = path.file_stem().and_then(|s| s.to_str()).unwrap_or("ui");
        let png_path = output_dir.join(format!("{stem}.png"));
        save_snapshot_png(&snapshot, &png_path)?;
        rendered.push(RenderEntry {
            stem: stem.to_owned(),
            yaml: format!("protov-hal-mock/states/{file_name}"),
            png: format!("docs/res/ui/{stem}.png"),
            description: snapshot.description,
        });
        println!("rendered {}", png_path.display());
    }

    write_ui_states_doc(&rendered, &doc_path)?;
    Ok(())
}

struct RenderEntry {
    stem: String,
    yaml: String,
    png: String,
    description: String,
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum FlowSection {
    NormalBoot,
    NormalMainStandalone,
    NormalComputerLinked,
    NormalFirmwareUpdate,
    TroubleshootingBoot,
    TroubleshootingProtection,
    TroubleshootingFirmware,
}

fn flow_section(stem: &str) -> FlowSection {
    match stem {
        "ui-boot-sense-fail" | "ui-boot-converter-fail" => FlowSection::TroubleshootingBoot,
        "ui-dfu-failed" => FlowSection::TroubleshootingFirmware,
        s if s.starts_with("ui-main-protection-") => FlowSection::TroubleshootingProtection,
        "ui-main-serial-connected" | "ui-main-custom-colors" => FlowSection::NormalComputerLinked,
        s if s.starts_with("ui-dfu-") => FlowSection::NormalFirmwareUpdate,
        s if s.starts_with("ui-boot-") => FlowSection::NormalBoot,
        _ => FlowSection::NormalMainStandalone,
    }
}

fn section_title(section: FlowSection) -> &'static str {
    match section {
        FlowSection::NormalBoot => "Normal flow — boot",
        FlowSection::NormalMainStandalone => "Normal flow — main screen (PD / front panel)",
        FlowSection::NormalComputerLinked => "Normal flow — computer linked",
        FlowSection::NormalFirmwareUpdate => "Normal flow — firmware update",
        FlowSection::TroubleshootingBoot => "Troubleshooting — boot self-check failed",
        FlowSection::TroubleshootingProtection => "Troubleshooting — protection latched",
        FlowSection::TroubleshootingFirmware => "Troubleshooting — firmware update failed",
    }
}

fn write_ui_states_doc(entries: &[RenderEntry], doc_path: &Path) -> Result<(), StateLoadError> {
    let mut body = String::from(
        "# ProtoV MINI UI state catalog\n\n\
         Generated by `just render-ui`. Each PNG is produced headlessly from the matching YAML state in \
         [`protov-hal-mock/states/`](../protov-hal-mock/states/).\n\n\
         For narrative walkthroughs with button sequences, see:\n\n\
         - [Interface guide](interface_guide.md) — normal PD and computer-linked flows\n\
         - [Troubleshooting](troubleshooting.md) — faults, limits, and protection\n\n",
    );

    let mut sections = [
        FlowSection::NormalBoot,
        FlowSection::NormalMainStandalone,
        FlowSection::NormalComputerLinked,
        FlowSection::NormalFirmwareUpdate,
        FlowSection::TroubleshootingBoot,
        FlowSection::TroubleshootingProtection,
        FlowSection::TroubleshootingFirmware,
    ];
    sections.sort();

    for section in sections {
        let mut group: Vec<&RenderEntry> = entries
            .iter()
            .filter(|e| flow_section(&e.stem) == section)
            .collect();
        if group.is_empty() {
            continue;
        }
        group.sort_by(|a, b| a.stem.cmp(&b.stem));

        body.push_str(&format!("## {}\n\n", section_title(section)));
        body.push_str(
            "| Render | State file | Description |\n|--------|------------|-------------|\n",
        );
        for entry in group {
            body.push_str(&format!(
                "| ![{}](res/ui/{}.png) | [`{}`](../{}) | {} |\n",
                entry.description, entry.stem, entry.yaml, entry.yaml, entry.description,
            ));
        }
        body.push('\n');
    }

    std::fs::write(doc_path, body).map_err(|source| StateLoadError::Io {
        path: doc_path.to_path_buf(),
        source,
    })?;
    Ok(())
}
